/**
 * page-transitions-gen.ts — generates the Page Effects RUNTIME into user source.
 *
 * Three files are scaffolded next to the route group's LayoutClient (so they
 * deploy as ordinary source — no backend change, source = deploy reality):
 *   - page-effects.ts          → the PAGE_EFFECTS data map (editor writes this)
 *   - page-effects-runtime.ts  → standalone pure helpers (resolve + CSS build),
 *                                a hand-mirrored copy of view-transition-css.ts
 *                                (a parity test guards against drift)
 *   - page-transitions.tsx     → the <PageTransitions> client controller
 * and `<PageTransitions>` is injected around `{children}` in the LayoutClient.
 *
 * ONE mechanism for preview + deploy: both are Next App Router SPA, so
 * document.startViewTransition() wrapping the route change (resolved on
 * usePathname change) works in both.
 */

