// src/code/audit/static/static-runner.test.ts
import { describe, it, expect } from 'vitest';
import { runStaticAudit } from './static-runner';

describe('Site Audit: Phase 1 Static AST Runner', () => {
  it('detects accessibility violations (missing-alt, accessible-name, positive-tabindex, roles)', async () => {
    const code = `
      export default function TestPage() {
        return (
          <main>
            <h1>Main Heading</h1>
            <img src="/hero.png" data-id="img-1" />
            <input type="image" src="/submit.png" data-id="inp-img" />
            <iframe src="https://example.com" data-id="frame-1" />
            <button data-id="btn-empty"></button>
            <input type="text" id="username" data-id="inp-user" />
            <label htmlFor="non-existent">Label for ghost</label>
            <div id="duplicate-1" data-id="d1">One</div>
            <div id="duplicate-1" data-id="d2">Two</div>
            <div tabIndex={5} data-id="tab-bad">Positive tab</div>
            <button aria-hidden="true" data-id="hidden-btn">Hidden but focusable</button>
            <div role="fake-role" data-id="bad-role">Bad role</div>
            <div role="checkbox" data-id="missing-checked">Missing aria-checked</div>
          </main>
        );
      }
    `;

    const result = await runStaticAudit({
      pagePath: 'app/page.tsx',
      scopes: ['accessibility'],
      fileMap: { 'app/page.tsx': code },
    });

    const ruleIds = result.findings.map((f) => f.ruleId);
    expect(ruleIds).toContain('missing-alt');
    expect(ruleIds).toContain('missing-image-input-alt');
    expect(ruleIds).toContain('missing-iframe-title');
    expect(ruleIds).toContain('missing-accessible-name');
    expect(ruleIds).toContain('missing-form-label');
    expect(ruleIds).toContain('invalid-label-reference');
    expect(ruleIds).toContain('duplicate-id');
    expect(ruleIds).toContain('positive-tabindex');
    expect(ruleIds).toContain('aria-hidden-focusable');
    expect(ruleIds).toContain('invalid-aria-role');
    expect(ruleIds).toContain('missing-required-aria-role-property');
    expect(result.summary.bySeverity.error).toBeGreaterThan(0);
  });

  it('detects heading hierarchy issues (missing-heading, multiple-headings, skipped-level)', async () => {
    const code = `
      export default function HeadingsPage() {
        return (
          <main>
            <h1>First Title</h1>
            <h1>Second Duplicate H1</h1>
            <h4>Skipped to H4</h4>
          </main>
        );
      }
    `;

    const result = await runStaticAudit({
      pagePath: 'app/page.tsx',
      scopes: ['accessibility'],
      fileMap: { 'app/page.tsx': code },
    });

    const ruleIds = result.findings.map((f) => f.ruleId);
    expect(ruleIds).toContain('multiple-page-headings');
    expect(ruleIds).toContain('skipped-heading-level');
  });

  it('detects SEO metadata issues and JSON-LD schema issues', async () => {
    const code = `
      export const metadata = {
        title: 'Untitled',
        description: 'Short',
      };

      export default function SeoPage() {
        return (
          <main>
            <h1>Welcome</h1>
            <script
              type="application/ld+json"
              dangerouslySetInnerHTML={{ __html: '{"@type": "UnknownRandomType"}' }}
            />
          </main>
        );
      }
    `;

    const result = await runStaticAudit({
      pagePath: 'app/page.tsx',
      scopes: ['seo'],
      fileMap: { 'app/page.tsx': code },
    });

    const ruleIds = result.findings.map((f) => f.ruleId);
    expect(ruleIds).toContain('empty-page-title');
    expect(ruleIds).toContain('weak-page-description');
    expect(ruleIds).not.toContain('missing-canonical'); // Canonical is auto-generated by Revyme export pipeline
    expect(ruleIds).toContain('missing-social-image-asset');
    expect(ruleIds).toContain('missing-json-ld-context');
    expect(ruleIds).toContain('unknown-schema-org-type');
  });

  it('detects cross-page title and description collisions', async () => {
    const pageA = `
      export const metadata = {
        title: 'Duplicate Title',
        description: 'This is an exact duplicate description across pages that needs to be unique for SEO.',
      };
      export default function PageA() { return <main><h1>Page A</h1></main>; }
    `;
    const pageB = `
      export const metadata = {
        title: 'Duplicate Title',
        description: 'This is an exact duplicate description across pages that needs to be unique for SEO.',
      };
      export default function PageB() { return <main><h1>Page B</h1></main>; }
    `;

    const result = await runStaticAudit({
      scopes: ['seo'],
      fileMap: {
        'app/a/page.tsx': pageA,
        'app/b/page.tsx': pageB,
      },
    });

    const ruleIds = result.findings.map((f) => f.ruleId);
    expect(ruleIds).toContain('duplicate-page-title');
    expect(ruleIds).toContain('duplicate-page-description');
  });

  it('detects security flaws (target-blank without noopener, dangerous external links)', async () => {
    const code = `
      export default function SecPage() {
        return (
          <main>
            <h1>Security</h1>
            <a href="https://partner.com" target="_blank" data-id="ext-link">External</a>
            <a href="http://unencrypted.com/data" data-id="http-link">HTTP link</a>
          </main>
        );
      }
    `;

    const result = await runStaticAudit({
      pagePath: 'app/page.tsx',
      scopes: ['security'],
      fileMap: { 'app/page.tsx': code },
    });

    const ruleIds = result.findings.map((f) => f.ruleId);
    expect(ruleIds).toContain('target-blank-without-noopener');
    expect(ruleIds).toContain('dangerous-external-link');
  });

  it('reports a clean pass when pages comply with all static standards', async () => {
    const code = `
      export const metadata = {
        title: 'Revyme Visual Website Builder for Next.js Developers',
        description: 'A comprehensive production-grade visual website builder with real Next.js source code synchronization.',
        alternates: { canonical: 'https://revyme.dev/features' },
        openGraph: { images: ['https://revyme.dev/og.png'] },
      };

      export default function CleanPage() {
        return (
          <main>
            <h1>Clean Semantic Heading</h1>
            <p>Welcome to our accessible, SEO-optimized website.</p>
            <img src="/logo.svg" alt="Revyme Logo" width={200} height={50} data-id="logo" />
            <a href="https://example.com" target="_blank" rel="noopener noreferrer">Visit Example</a>
          </main>
        );
      }
    `;

    const result = await runStaticAudit({
      pagePath: 'app/page.tsx',
      scopes: ['accessibility', 'seo', 'security'],
      fileMap: { 'app/page.tsx': code },
    });

    expect(result.findings.filter((f) => f.severity === 'error')).toHaveLength(0);
    expect(result.summary.scores?.accessibility).toBeGreaterThanOrEqual(90);
    expect(result.summary.scores?.seo).toBeGreaterThanOrEqual(90);
  });
});
